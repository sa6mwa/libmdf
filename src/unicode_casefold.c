size_t mdf_unicode_casefold(unsigned long codepoint, unsigned long folded[3])
{
    size_t lower;
    size_t upper;

    lower = 0;
    upper = sizeof(mdf_unicode_casefold_entries) / sizeof(mdf_unicode_casefold_entries[0]);
    while (lower < upper) {
        size_t middle;
        const mdf_unicode_casefold_entry *entry;

        middle = lower + (upper - lower) / 2;
        entry = &mdf_unicode_casefold_entries[middle];
        if (codepoint < entry->codepoint) {
            upper = middle;
        } else if (codepoint > entry->codepoint) {
            lower = middle + 1;
        } else {
            size_t i;

            for (i = 0; i < entry->len; i++) folded[i] = entry->folded[i];
            return entry->len;
        }
    }
    folded[0] = codepoint;
    return 1;
}
